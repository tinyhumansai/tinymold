def hit_section(result: dict) -> list[str]:
    """Cache hits on many-output units: one tinymold revision against another."""
    rows = result["results"]
    lines = [f"### Cache hits on many-output units ({describe(result)})", "",
             "Every source file touched, then rebuilt through the wrapper, so each "
             "workspace unit is a cache hit. Incremental units with "
             + ", ".join(f"`{value}`" for value in result["config"])
             + " keep one object file per codegen unit, so a hit places hundreds of "
             "files. Before is the `--against` revision, after is the checkout's; they "
             "take alternate turns on the same store. Restore times come from "
             "`TINYMOLD_TRACE`; cells are medians (min–max). A crate's row adds up all "
             "of its units, such as a library and a binary of the same name.", "",
             "| Project | What | before | after | change |",
             "| --- | --- | ---: | ---: | ---: |"]

    def cell(stats: dict, scale: float, unit: str, digits: int) -> str:
        return (f"{stats['median_s'] * scale:.{digits}f}{unit} "
                f"({stats['min_s'] * scale:.{digits}f}–{stats['max_s'] * scale:.{digits}f})")

    for project in dict.fromkeys(r["project"] for r in rows):
        mine = [r for r in rows if r["project"] == project]
        before, after = mine[0], mine[-1]
        name = f"{project} {before['rev']}<br>tinymold {before['tinymold']} → {after['tinymold']}"
        measures = [("Build wall time", lambda r: r["wall"], 1, "s", 2),
                    (f"All {before['hits']:.0f} restores, summed", lambda r: r["restore"],
                     1000, " ms", 0)]
        for unit in before["units"][:3]:
            def pick(r: dict, crate: str = unit["crate"]) -> dict:
                return next(u["restore"] for u in r["units"] if u["crate"] == crate)
            measures.append((f"`{unit['crate']}` restore ({unit['files']} files)", pick,
                             1000, " ms", 1))
        for label, pick, scale, unit, digits in measures:
            old, new = pick(before), pick(after)
            change = f"{new['median_s'] / old['median_s'] - 1:+.0%}" if old["median_s"] else "–"
            lines.append(f"| {name} | {label} | {cell(old, scale, unit, digits)} | "
                         f"{cell(new, scale, unit, digits)} | {change} |")
    return lines + [""]


def retest_section(result: dict) -> list[str]:
    """`cargo test` run again, with and without `tinymold run-test`."""
    rows = result["results"]
    lines = [f"### Running tests again ({describe(result)})", "",
             "`cargo test` for the project's package, built through `RUSTC_WRAPPER=tinymold` "
             "on both sides; only the runner differs. *again*: nothing changed. "
             "*private_body*: a one-line private edit before every run. Cells are median wall "
             "time (min–max) and test binaries replayed / run by `tinymold run-test`; "
             "*runs* is how many measurements each side took.", ""]
    settings = result.get("settings", {})
    if settings:
        lines += ["Settings: " + "; ".join(f"{k.replace('_', ' ')}: {v}"
                                          for k, v in settings.items()) + ".", ""]
    lines += ["| Project | Case | runs | cargo | run-test | replayed / ran | change |",
              "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]

    def cell(stats: dict) -> str:
        return f"{stats['median_s']:.2f}s ({stats['min_s']:.2f}–{stats['max_s']:.2f})"

    for project in dict.fromkeys(r["project"] for r in rows):
        for case in dict.fromkeys(r["case"] for r in rows if r["project"] == project):
            pick = {r["mode"]: r for r in rows if r["project"] == project and r["case"] == case}
            if not {"cargo", "run-test"} <= set(pick):
                continue
            old, new = pick["cargo"], pick["run-test"]
            change = f"{new['wall']['median_s'] / old['wall']['median_s'] - 1:+.0%}"
            runs = "/".join(map(str, dict.fromkeys((runs_of(result, old), runs_of(result, new)))))
            lines.append(f"| {project} {old['rev']} | {case} | {runs} | {cell(old['wall'])} | "
                         f"{cell(new['wall'])} | {new['replayed']:.0f} / {new['ran']:.0f} | "
                         f"{change} |")
    return lines + [""]


EDIT_COMMANDS = (("build", "build"), ("clippy", "clippy"), ("test_build", "test build"),
                 ("test_run", "test run"), ("coverage", "coverage"))


def edit_steps(steps: list[dict], kinds=("comment", "private_body", "public_signature")):
    return [s for s in steps if s["edit"] in kinds]


def median(values: list[float]) -> float | None:
    return statistics.median(values) if values else None


def seconds(value: float | None) -> str:
    return "–" if value is None else f"{value:.2f}s"


def growth_chart(title: str, series: dict[str, list[tuple[int, float]]], path: Path) -> None:
    """A light/dark-safe line chart of MiB against step, one line per series."""
    width, height, left, top, bottom = 640, 260, 60, 30, 30
    colors = ("#4c78a8", "#f58518", "#54a24b", "#e45756", "#72b7b2", "#b279a2")
    points = [p for line in series.values() for p in line]
    xmax = max((x for x, _ in points), default=1) or 1
    ymax = max((y for _, y in points), default=1.0) or 1.0
    plot_w, plot_h = width - left - 160, height - top - bottom

    def at(x: float, y: float) -> str:
        return f"{left + plot_w * x / xmax:.1f},{top + plot_h * (1 - y / ymax):.1f}"

    parts = [f'<text x="0" y="18" font-weight="bold">{escape(title)}</text>',
             f'<text x="{left - 8}" y="{top + 5}" text-anchor="end">{ymax:,.0f}</text>',
             f'<text x="{left - 8}" y="{top + plot_h}" text-anchor="end">0 MiB</text>',
             f'<text x="{left + plot_w}" y="{height - 8}" text-anchor="end">step {xmax}</text>',
             f'<line x1="{left}" y1="{top + plot_h}" x2="{left + plot_w}" y2="{top + plot_h}" '
             'stroke="#888"/>']
    for i, (label, line) in enumerate(series.items()):
        color = colors[i % len(colors)]
        parts.append(f'<polyline fill="none" stroke="{color}" stroke-width="2" points="'
                     + " ".join(at(x, y) for x, y in line) + '"/>')
        parts.append(f'<text x="{left + plot_w + 10}" y="{top + 16 * i + 10}" '
                     f'fill="{color}">{escape(label)}</text>')
    path.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
                    'font-family="system-ui, sans-serif" font-size="13" fill="#888">'
                    + "".join(parts) + "</svg>\n")


def edits_section(name: str, result: dict) -> list[str]:
    """The cumulative edit sequence: latency per command, then footprint."""
    rows = result["results"]
    lines = [f"### Edit sequence ({describe(result)})", "",
             f"{len(rows[0]['steps']) - 1 if rows else 0} cumulative steps per project "
             f"({result['schedule']}), each followed by: {', '.join(result['commands'])}. "
             "Latency cells are medians over the edit steps; *after fresh* is the first edit "
             "after the target directory was deleted with the store kept. Sizes are "
             "allocated blocks with each inode counted once, so reflinked files count in "
             "full; growth is per step after the warm-up build. Peak RSS is the largest "
             "single process (rustc, linker or wrapper) of any command.", "",
             "| Project | Mode | " + " | ".join(label for _, label in EDIT_COMMANDS)
             + " | fresh build | after fresh |",
             "| --- | --- |" + " ---: |" * (len(EDIT_COMMANDS) + 2)]
    footprint = ["", "| Project | Mode | target/ final | target/ per step | incremental final "
                 "| coverage final | store final | store per step | store after gc | peak RSS |",
                 "| --- | --- |" + " ---: |" * 8]
    charts = [""]
    for project in dict.fromkeys(r["project"] for r in rows):
        mine = [r for r in rows if r["project"] == project]
        series: dict[str, list[tuple[int, float]]] = {}
        for r in mine:
            steps, edited = r["steps"], edit_steps(r["steps"])
            cells = []
            for key, _ in EDIT_COMMANDS:
                cells.append(seconds(median([s["commands"][key]["wall_s"] for s in edited
                                             if key in s["commands"]])))
            fresh = [i for i, s in enumerate(steps) if s["edit"] == "fresh"]
            fresh_build = median([steps[i]["commands"]["build"]["wall_s"] for i in fresh
                                  if "build" in steps[i]["commands"]])
            after = median([steps[i + 1]["commands"]["build"]["wall_s"] for i in fresh
                            if i + 1 < len(steps) and "build" in steps[i + 1]["commands"]])
            label = f"{project} {r['rev']}"
            lines.append(f"| {label} | {r['mode']} | " + " | ".join(cells)
                         + f" | {seconds(fresh_build)} | {seconds(after)} |")
            first, last = steps[0], steps[-1]
            count = max(1, len(steps) - 1)

            def size(step: dict, *path: str) -> int:
                value = step
                for key in path:
                    value = value.get(key, {})
                return value.get("allocated", 0) if isinstance(value, dict) else 0

            target_growth = (size(last, "target", "total") - size(first, "target", "total")) / count
            store_growth = (size(last, "store") - size(first, "store")) / count
            rss = max(c["rss_mb"] for s in steps for c in s["commands"].values())
            has_store = "store" in first
            footprint.append(
                f"| {label} | {r['mode']} | {mib(size(last, 'target', 'total'))} | "
                f"{mib(int(target_growth))} | {mib(size(last, 'target', 'incremental'))} | "
                f"{mib(size(last, 'target', 'coverage'))} | "
                f"{mib(size(last, 'store')) if has_store else '–'} | "
                f"{mib(int(store_growth)) if has_store else '–'} | "
                f"{mib(size(last, 'store_after_gc')) if 'store_after_gc' in last else '–'} | "
                f"{rss:,.0f} MiB |")
            series[f"{r['mode']} target/"] = [(s["step"], size(s, "target", "total") / 2**20)
                                              for s in steps]
            if has_store:
                series[f"{r['mode']} store"] = [(s["step"], size(s, "store") / 2**20)
                                                for s in steps]
            if "store_after_gc" in last:
                series[f"{r['mode']} store after gc"] = [
                    (s["step"], size(s, "store_after_gc") / 2**20) for s in steps]
        svg = RESULTS / f"{name}-{project}.svg"
        growth_chart(f"{project}: target/ and store size by step (MiB allocated)", series, svg)
        charts += [f"![{project} size by step](results/{svg.name})", ""]
    return lines + footprint + charts


COMMAND_LABELS = {"build": "build", "clippy": "clippy", "test_build": "test build",
                  "test_run": "test run", "coverage": "coverage"}


def warm_median(r: dict, case: str, label: str) -> float | None:
    entry = r.get(case, {}).get(label)
    return entry["wall"]["median_s"] if entry else None


def commands_rows(result: dict):
    """(project, rev, label, {mode: row}) for every command label measured."""
    rows = result["results"]
    for project in dict.fromkeys(r["project"] for r in rows):
        mine = [r for r in rows if r["project"] == project]
        for label in COMMAND_LABELS:
            by_mode = {r["mode"]: r for r in mine if label in r.get("cold", {})}
            if by_mode:
                yield project, mine[0]["rev"], label, by_mode


# Labels no cache serves today: a ratio there is noise, not a speed-up.
UNCACHED = ("test_run",)


def speedup(before: float | None, after: float | None, label: str = "") -> str:
    if label in UNCACHED:
        return "not cached"
    return "–" if not before or not after else f"{before / after:.1f}×"


def commands_section(name: str, result: dict) -> list[str]:
    """Per command: plain cargo, then each cache cold and warm."""
    modes = result.get("modes", ["baseline", "sccache", "tinymold"])
    cached = [m for m in modes if m != "baseline"]
    lines = [f"### Cache per command ({describe(result)})", "",
             "Each command starts from an empty target directory and an empty cache. "
             "*Cold* is that first run, which fills the cache; *warm* deletes the "
             "target directory, keeps the cache and runs the command again: a CI runner "
             "that restored its cache, a new worktree or a `cargo clean`. Plain cargo "
             "has no cache, so its cell is the cold median. Cells are median wall time; "
             "tinymold's warm cell adds rustc invocations served from the store across all "
             "runs. *Speed-up* is plain cargo over tinymold warm. `test run` is "
             "plain `cargo test` executing the tests, with no `tinymold run-test` "
             "runner, so no side caches it here; the `retest` benchmark measures "
             "replaying test runs.", "",
             "| Project | Command | " + " | ".join(
                 ["plain cargo"] + [f"{m} {case}" for m in cached for case in ("cold", "warm")])
             + " | speed-up |",
             "| --- | --- |" + " ---: |" * (2 + 2 * len(cached))]
    for project, rev, label, by_mode in commands_rows(result):
        base = by_mode.get("baseline")
        cells = [seconds(warm_median(base, "cold", label)) if base else "–"]
        for mode in cached:
            r = by_mode.get(mode)
            for case in ("cold", "warm"):
                cell = seconds(warm_median(r, case, label)) if r else "–"
                stats = r[case][label].get("cache") if r else None
                if case == "warm" and stats and stats["hits"] + stats["misses"]:
                    cell += f" ({stats['hits']}/{stats['hits'] + stats['misses']} hits)"
                cells.append(cell)
        tiny = by_mode.get("tinymold")
        ratio = speedup(warm_median(base, "cold", label) if base else None,
                        warm_median(tiny, "warm", label) if tiny else None, label)
        lines.append(f"| {project} {rev} | {COMMAND_LABELS[label]} | "
                     + " | ".join(cells) + f" | {ratio} |")
    lines.append("")
    svg = RESULTS / f"{name}.svg"
    commands_chart(result, svg)
    return lines + [f"![Cache per command](results/{svg.name})", ""]


def commands_chart(result: dict, path: Path) -> None:
    groups = []
    for project, _rev, label, by_mode in commands_rows(result):
        bars = []
        for mode, case, name in (("baseline", "cold", "plain cargo"),
                                 ("sccache", "warm", "sccache, warm"),
                                 ("tinymold", "warm", "tinymold, warm")):
            value = warm_median(by_mode[mode], case, label) if mode in by_mode else None
            if value is not None:
                bars.append((name, value))
        groups.append((f"{project} · {COMMAND_LABELS[label]}", bars))
    paired_chart("Fresh target directory, warm cache (median wall time, shorter is better)",
                 groups, path)


def commands_summary(name: str, result: dict) -> list[str]:
    """The top-level README's table: plain cargo against tinymold warm."""
    m = result["machine"]
    lines = ["| Project | Command | plain cargo | tinymold, warm cache | speed-up |",
             "| --- | --- | ---: | ---: | ---: |"]
    for project, rev, label, by_mode in commands_rows(result):
        if "baseline" not in by_mode or "tinymold" not in by_mode:
            continue
        before = warm_median(by_mode["baseline"], "cold", label)
        after = warm_median(by_mode["tinymold"], "warm", label)
        lines.append(f"| {project} {rev} | `{COMMAND_LABELS[label]}` | {seconds(before)} | "
                     f"{seconds(after)} | {speedup(before, after, label)} |")
    return lines + ["", f"Median of {result['runs']} runs on {m['os']} {m['arch']}, "
                    f"{m['cpus']} CPUs, {m['rustc']}, {result['date']}; generated by "
                    "`bench/report.py` from "
                    f"[`bench/results/{name}.json`](bench/results/{name}.json).", "",
                    f"![Cache per command](bench/results/{name}.svg)"]


def render_root_readme(summary: list[str]) -> None:
    text = ROOT_README.read_text()
