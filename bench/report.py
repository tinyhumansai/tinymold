def mib(n: int | None) -> str:
    return "n/a" if n is None else f"{n / 2**20:,.0f} MiB"


def runs_of(result: dict, row: dict) -> int:
    """How many runs a row's numbers come from: its own count, which a merged
    file records per row, or else the file's."""
    return row.get("runs", result["runs"])


def describe(result: dict) -> str:
    m = result["machine"]
    counts = sorted({runs_of(result, r) for r in result.get("results", [])}) or [result["runs"]]
    runs = (f"{counts[0]} runs" if len(counts) == 1
            else f"{'/'.join(map(str, counts))} runs by row")
    return (f"{m['os']} {m['arch']}, {m['cpus']} CPUs, {m['rustc']}, "
            f"{runs}, {result['date']}")


def chart(title: str, bars: list[tuple[str, float]], path: Path) -> None:
    """A light/dark-safe horizontal bar chart; shorter bars are faster."""
    width, label_w, bar_h, gap, top = 640, 150, 26, 10, 40
    longest = max(value for _, value in bars) or 1.0
    usable = width - label_w - 90
    height = top + len(bars) * (bar_h + gap) + 10
    rows = []
    for i, (label, value) in enumerate(bars):
        y = top + i * (bar_h + gap)
        w = max(2.0, usable * value / longest)
        rows.append(
            f'<text x="{label_w - 10}" y="{y + bar_h * 0.7}" text-anchor="end">{escape(label)}</text>'
            f'<rect x="{label_w}" y="{y}" width="{w:.1f}" height="{bar_h}" rx="3" fill="#4c78a8"/>'
            f'<text x="{label_w + w + 8:.1f}" y="{y + bar_h * 0.7}">{value:.2f}s</text>')
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
           f'font-family="system-ui, sans-serif" font-size="14" fill="#888">'
           f'<text x="0" y="22" font-weight="bold">{escape(title)}</text>'
           + "".join(rows) + "</svg>\n")
    path.write_text(svg)


def paired_chart(title: str, groups: list[tuple[str, list[tuple[str, float]]]],
                 path: Path) -> None:
    """A light/dark-safe horizontal bar chart with one bar per series in each
    group, colored by series, with a legend; shorter bars are faster."""
    width, label_w, bar_h, gap, top = 680, 170, 14, 12, 52
    colors = ("#9e9e9e", "#f58518", "#4c78a8")
    series = list(dict.fromkeys(name for _, bars in groups for name, _ in bars))
    longest = max((value for _, bars in groups for _, value in bars), default=1.0) or 1.0
    usable = width - label_w - 70
    group_h = bar_h * max(len(bars) for _, bars in groups) if groups else 0
    height = top + len(groups) * (group_h + gap) + 6
    parts = [f'<text x="0" y="20" font-weight="bold">{escape(title)}</text>']
    for i, name in enumerate(series):
        x = label_w + i * 150
        parts.append(f'<rect x="{x}" y="30" width="12" height="12" rx="2" '
                     f'fill="{colors[i % len(colors)]}"/>'
                     f'<text x="{x + 18}" y="41">{escape(name)}</text>')
    for g, (label, bars) in enumerate(groups):
        y0 = top + g * (group_h + gap)
        parts.append(f'<text x="{label_w - 10}" y="{y0 + group_h / 2 + 5:.1f}" '
                     f'text-anchor="end">{escape(label)}</text>')
        for name, value in bars:
            i = series.index(name)
            y = y0 + bars.index((name, value)) * bar_h
            w = max(2.0, usable * value / longest)
            parts.append(f'<rect x="{label_w}" y="{y}" width="{w:.1f}" height="{bar_h - 2}" '
                         f'rx="2" fill="{colors[i % len(colors)]}"/>'
                         f'<text x="{label_w + w + 6:.1f}" y="{y + bar_h - 3}" '
                         f'font-size="11">{value:.1f}s</text>')
    path.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
                    'font-family="system-ui, sans-serif" font-size="13" fill="#888">'
                    + "".join(parts) + "</svg>\n")


def link_section(name: str, result: dict) -> list[str]:
    rows = result["results"]
    lines = [f"### Edit-rebuild loop ({describe(result)})", ""]
    for project in dict.fromkeys(r["project"] for r in rows):
        mine = [r for r in rows if r["project"] == project]
        svg = RESULTS / f"{name}-{project}.svg"
        chart(f"{project}: rebuild after a one-line edit (median, shorter is better)",
              [(r["linker"], r["edit_rebuild"]["median_s"]) for r in mine], svg)
        lines += [f"![{project} edit-rebuild by linker](results/{svg.name})", "",
                  "| Project | Linker | Edit → rebuilt binary (median) | min–max | Full build | Binary | target/ |",
                  "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
        for r in mine:
            e = r["edit_rebuild"]
            lines.append(
                f"| {project} {r['rev']} | {r['linker']} | {e['median_s']:.2f}s | "
                f"{e['min_s']:.2f}–{e['max_s']:.2f}s | {r['full_build_s']:.1f}s | "
                f"{mib(r['binary_bytes'])} | {mib(r['target_bytes'])} |")
        lines.append("")
    return lines


